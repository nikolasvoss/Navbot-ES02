// Queues each frame on a LinkPort of its own, as the firmware does, so seq comes from the real code path.
class QueueSink : public LinkMessageSink {
 public:
  QueueSink() : ports_{{storage_[0], sizeof(storage_[0]), false}, {storage_[1], sizeof(storage_[1]), true}} {}
  void Send(uint8_t port, navbot_link_v1_Message& msg) override { LinkPortSend(ports_[port], msg, 42); }
  // The next frame queued for the port, or empty.
  std::vector<uint8_t> Take(uint8_t port) {
    uint8_t tag = 0;
    uint8_t buffer[LINK_MAX_ITEM_LEN];
    size_t len = 0;
    if (!ports_[port].queue.Pop(tag, buffer, len)) return {};
    return std::vector<uint8_t>(buffer, buffer + len);
  }

 private:
  uint8_t storage_[2][4096];
  LinkPort ports_[2];
};

bool failed = false;

void Check(bool condition, const char* what) {
  std::printf("%s: %s\n", what, condition ? "ok" : "FAIL");
  if (!condition) failed = true;
}

// The queued frame is a Log with this tag and text.
bool LogIs(const std::vector<uint8_t>& frame, const char* tag, const char* text) {
  struct Payloads : LinkRxSink {
    std::vector<std::vector<uint8_t>> items;
    void OnPayload(const uint8_t* payload, size_t len) override { items.emplace_back(payload, payload + len); }
  } rx;
  LinkRxDecoder decoder;
  decoder.Feed(frame.data(), frame.size(), rx);
  navbot_link_v1_Message msg;
  return rx.items.size() == 1 && LinkDecodeMessage(rx.items[0].data(), rx.items[0].size(), msg) &&
         msg.which_body == navbot_link_v1_Message_log_tag && std::strcmp(msg.body.log.tag, tag) == 0 &&
         std::strcmp(msg.body.log.text, text) == 0;
}

template <size_t N>
bool Is(const std::vector<uint8_t>& actual, const uint8_t (&expected)[N]) {
  return actual.size() == N && std::memcmp(actual.data(), expected, N) == 0;
}

