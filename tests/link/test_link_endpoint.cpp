// The first message in a queued frame, decoded.
navbot_link_v1_Message DecodeOne(const std::vector<uint8_t>& frame) {
  struct Payloads : LinkRxSink {
    std::vector<std::vector<uint8_t>> items;
    void OnPayload(const uint8_t* payload, size_t len) override { items.emplace_back(payload, payload + len); }
  } rx;
  LinkRxDecoder decoder;
  decoder.Feed(frame.data(), frame.size(), rx);
  navbot_link_v1_Message msg = navbot_link_v1_Message_init_zero;
  if (rx.items.size() == 1) LinkDecodeMessage(rx.items[0].data(), rx.items[0].size(), msg);
  return msg;
}

// The frame is an accepted Ack whose value is the given slot.
bool AckGivesSlot(const std::vector<uint8_t>& frame, uint32_t slot) {
  const navbot_link_v1_Message msg = DecodeOne(frame);
  const uint8_t* b = msg.body.ack.value.bytes;
  const uint32_t value = static_cast<uint32_t>(b[0]) | static_cast<uint32_t>(b[1]) << 8 |
                         static_cast<uint32_t>(b[2]) << 16 | static_cast<uint32_t>(b[3]) << 24;
  return msg.which_body == navbot_link_v1_Message_ack_tag && msg.body.ack.accepted && msg.body.ack.value.size == 4 &&
         value == slot;
}

