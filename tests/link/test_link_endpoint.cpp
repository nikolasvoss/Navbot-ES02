// Accepts 0 to 1. The sketch's settings groups do the same through PARAM and their apply functions.
bool WriteGain(uint32_t bits, const char** error) {
  float value = 0.0f;
  *error = SignalFromBits(bits, value);
  if (*error == nullptr && (value < 0.0f || value > 1.0f)) *error = "must be within [0, 1]";
  if (*error != nullptr) return false;
  gGain = value;
  return true;
}

uint32_t Bits(float value) {
  uint32_t bits;
  std::memcpy(&bits, &value, sizeof(bits));
  return bits;
}

